use std::fs;

use tempfile::TempDir;
use ts_typegen_build::config::Config;
use ts_typegen_build::run::generate;

fn project(files: &[(&str, &str)]) -> TempDir {
    let dir = tempfile::tempdir().unwrap();
    for (path, body) in files {
        let full = dir.path().join(path);
        fs::create_dir_all(full.parent().unwrap()).unwrap();
        fs::write(full, body).unwrap();
    }
    dir
}

#[test]
fn end_to_end_from_source_to_files() {
    let dir = project(&[(
        "src/lib.rs",
        "#[derive(Ts)] pub struct Address { pub city: String }\n\
         #[derive(Ts)] #[serde(rename_all = \"camelCase\")] \
         pub struct User { pub user_id: u64, pub address: Address }\n",
    )]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .always_run(true);

    let outcome = generate(&cfg).expect("generation must succeed");
    assert!(!outcome.skipped);

    let user = fs::read_to_string(dir.path().join("bindings/User.ts")).unwrap();
    assert!(user.starts_with("// @generated by ts-typegen -- DO NOT EDIT"));
    assert!(user.contains("import type { Address } from \"./Address\";"));
    assert!(user.contains("userId: number;"));
    assert!(user.contains("address: Address;"));

    let index = fs::read_to_string(dir.path().join("bindings/index.ts")).unwrap();
    assert!(index.contains("export type { User } from \"./User\";"));
    assert!(index.contains("export type { Address } from \"./Address\";"));
}

#[test]
fn bigint_config_reaches_the_output() {
    let dir = project(&[("src/lib.rs", "#[derive(Ts)] pub struct S { pub v: u64 }\n")]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .bigint(ts_typegen_build::config::BigInt::Bigint)
        .always_run(true);
    generate(&cfg).unwrap();
    assert!(
        fs::read_to_string(dir.path().join("bindings/S.ts")).unwrap().contains("v: bigint;")
    );
}

#[test]
fn map_type_override_reaches_the_output() {
    let dir = project(&[("src/lib.rs", "#[derive(Ts)] pub struct S { pub id: uuid::Uuid }\n")]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .map_type("uuid::Uuid", "string")
        .always_run(true);
    generate(&cfg).unwrap();
    assert!(fs::read_to_string(dir.path().join("bindings/S.ts")).unwrap().contains("id: string;"));
}

#[test]
fn diagnostics_fail_the_build_and_name_every_problem() {
    let dir = project(&[(
        "src/lib.rs",
        "#[derive(Ts)] pub struct A { pub v: Ghost }\n\
         #[derive(Ts)] pub struct B { pub v: Phantom }\n",
    )]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .always_run(true);
    let err = generate(&cfg).expect_err("unknown types must fail");
    let msg = format!("{err}");
    assert!(msg.contains("Ghost"), "got: {msg}");
    assert!(msg.contains("Phantom"), "both problems must be reported: {msg}");
}

#[test]
fn renaming_a_type_sweeps_the_old_binding() {
    let dir = project(&[("src/lib.rs", "#[derive(Ts)] pub struct User { pub v: u8 }\n")]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .always_run(true);
    generate(&cfg).unwrap();
    assert!(dir.path().join("bindings/User.ts").is_file());

    fs::write(
        dir.path().join("src/lib.rs"),
        "#[derive(Ts)] pub struct Account { pub v: u8 }\n",
    )
    .unwrap();
    generate(&cfg).unwrap();
    assert!(!dir.path().join("bindings/User.ts").exists());
    assert!(dir.path().join("bindings/Account.ts").is_file());
}

#[test]
fn generation_is_skipped_for_non_primary_packages() {
    let dir = project(&[("src/lib.rs", "#[derive(Ts)] pub struct S { pub v: u8 }\n")]);
    // always_run defaults to false; CARGO_PRIMARY_PACKAGE is unset under `cargo test`.
    let cfg = Config::new().scan(dir.path().join("src")).output(dir.path().join("bindings"));
    let outcome = generate(&cfg).unwrap();
    assert!(outcome.skipped);
    assert!(!dir.path().join("bindings").exists());
}
