#[test]
fn a_cyclic_type_alias_is_a_diagnostic_not_a_hang() {
    let dir = project(&[(
        "src/lib.rs",
        "pub type A = B;\npub type B = A;\n#[derive(Ts)] pub struct S { pub v: A }\n",
    )]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .always_run(true);
    let err = generate(&cfg).expect_err("a cyclic alias cannot resolve to a real shape");
    assert!(format!("{err}").contains("defined in terms of itself"));
}

#[test]
fn diagnostics_fail_the_build_and_name_every_problem() {
    let dir = project(&[(
        "src/lib.rs",
        "#[derive(Ts)] pub struct A { pub v: Ghost }\n\
         #[derive(Ts)] pub struct B { pub v: Phantom }\n",
    )]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .always_run(true);
    let err = generate(&cfg).expect_err("unknown types must fail");
    let msg = format!("{err}");
    assert!(msg.contains("Ghost"), "got: {msg}");
    assert!(msg.contains("Phantom"), "both problems must be reported: {msg}");
}

#[test]
fn renaming_a_type_sweeps_the_old_binding() {
    let dir = project(&[("src/lib.rs", "#[derive(Ts)] pub struct User { pub v: u8 }\n")]);
    let cfg = Config::new()
        .scan(dir.path().join("src"))
        .output(dir.path().join("bindings"))
        .always_run(true);
    generate(&cfg).unwrap();
    assert!(dir.path().join("bindings/User.ts").is_file());

    fs::write(
        dir.path().join("src/lib.rs"),
        "#[derive(Ts)] pub struct Account { pub v: u8 }\n",
    )
    .unwrap();
    generate(&cfg).unwrap();
    assert!(!dir.path().join("bindings/User.ts").exists());
    assert!(dir.path().join("bindings/Account.ts").is_file());
}

#[test]
fn a_local_project_generates_without_always_run() {
    // The downstream-build gate must not fire for an ordinary project, or the
    // crate would silently do nothing for every user.
    let dir = project(&[("src/lib.rs", "#[derive(Ts)] pub struct S { pub v: u8 }\n")]);
    let cfg = Config::new().scan(dir.path().join("src")).output(dir.path().join("bindings"));
    let outcome = generate(&cfg).unwrap();
    assert!(!outcome.skipped, "generation must run for a local project");
    assert!(dir.path().join("bindings/S.ts").is_file());
}
