//! Assembling declarations into complete `.ts` files.
//!
//! Reference resolution is by final path segment against the registry, which is
//! sound because duplicate TypeScript names are already a hard error.

use std::collections::{BTreeMap, BTreeSet};

use crate::config::Config;
use crate::diag::{Diagnostic, Diagnostics};
use crate::emit::emit_decl;
use crate::ir::{Body, Decl, Registry, Ty, VariantKind};

pub const MARKER: &str = "// @generated by ts-typegen -- DO NOT EDIT";

pub fn render_all(
    reg: &Registry,
    cfg: &Config,
    diags: &mut Diagnostics,
) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();

    for decl in reg.decls() {
        let decl = &inline_fields(decl, reg, diags);
        let mut refs = BTreeSet::new();
        collect_refs(&decl.body, &mut refs);

        let mut imports = Vec::new();
        for name in &refs {
            if *name == decl.ts_name || decl.generics.contains(name) {
                continue;
            }
            if reg.lookup(name).is_none() {
                diags.push(
                    Diagnostic::new(decl.loc.clone(), format!("unknown type `{name}`")).with_help(
                        format!(
                            "add #[ts(type = \"...\")] to the field, or \
                             .map_type(\"path::{name}\", \"...\") in build.rs"
                        ),
                    ),
                );
                continue;
            }
            imports.push(format!(
                "import type {{ {name} }} from \"./{name}{}\";",
                cfg.extension()
            ));
        }

        let mut out = String::from(MARKER);
        out.push('\n');
        if !imports.is_empty() {
            out.push_str(&imports.join("\n"));
            out.push_str("\n\n");
        }
        out.push_str(&emit_decl(decl, cfg));
        files.insert(format!("{}.ts", decl.ts_name), out);
    }

    if cfg.index_enabled() {
        let mut out = String::from(MARKER);
        out.push('\n');
        // Sorted, not scan order: module traversal order is not stable across
        // platforms, and an unstable barrel would fail check mode spuriously.
        let mut names: Vec<&str> = reg.decls().iter().map(|d| d.ts_name.as_str()).collect();
        names.sort_unstable();
        for n in names {
            out.push_str(&format!(
                "export type {{ {n} }} from \"./{n}{ext}\";\n",
                ext = cfg.extension()
            ));
        }
        files.insert(cfg.index_file_name().to_string(), out);
    }

    files
}

/// Replaces `#[ts(inline)]` fields' references with the target's shape, so the
/// declaration stands alone and needs no import for them.
///
/// Substitution happens before reference collection, which is what removes the
/// import: an inlined type is no longer referenced by name.
fn inline_fields(decl: &Decl, reg: &Registry, diags: &mut Diagnostics) -> Decl {
    let Body::Struct(fields) = &decl.body else {
        return decl.clone();
    };
    if !fields.iter().any(|f| f.inline) {
        return decl.clone();
    }
    let mut out = decl.clone();
    let Body::Struct(fields) = &mut out.body else { unreachable!() };
    for f in fields.iter_mut() {
        if !f.inline {
            continue;
        }
        let Ty::Ref { name, .. } = &f.ty else {
            continue; // Inlining a primitive or container is a no-op.
        };
        let Some(target) = reg.lookup(name) else {
            continue; // Reported as an unknown type by the caller.
        };
        match body_as_ty(&target.body) {
            Some(ty) => f.ty = ty,
            None => diags.push(
                Diagnostic::new(
                    decl.loc.clone(),
                    format!("cannot inline `{name}`: enums have no inline object form"),
                )
                .with_help("drop #[ts(inline)] and let it be imported instead"),
            ),
        }
    }
    out
}

/// A declaration's shape as an anonymous type, when it has one. Enums render as
/// unions of tagged variants, which only the emitter can build, so they return
/// `None` rather than a wrong shape.
fn body_as_ty(body: &Body) -> Option<Ty> {
    Some(match body {
        Body::Struct(fields) => Ty::Object(fields.clone()),
        Body::Newtype(t) => t.clone(),
        Body::Tuple(items) => Ty::Tuple(items.clone()),
        Body::Unit => Ty::Prim(crate::ir::Prim::Null),
        Body::Enum { .. } => return None,
    })
}

fn collect_refs(body: &Body, out: &mut BTreeSet<String>) {
    match body {
        Body::Struct(fields) => fields.iter().for_each(|f| collect_ty_refs(&f.ty, out)),
        Body::Newtype(t) => collect_ty_refs(t, out),
        Body::Tuple(items) => items.iter().for_each(|t| collect_ty_refs(t, out)),
        Body::Unit => {}
        Body::Enum { variants, .. } => {
            for v in variants {
                match &v.kind {
                    VariantKind::Unit => {}
                    VariantKind::Newtype(t) => collect_ty_refs(t, out),
                    VariantKind::Tuple(items) => items.iter().for_each(|t| collect_ty_refs(t, out)),
                    VariantKind::Struct(fields) => {
                        fields.iter().for_each(|f| collect_ty_refs(&f.ty, out))
                    }
                }
            }
        }
    }
}

fn collect_ty_refs(ty: &Ty, out: &mut BTreeSet<String>) {
    match ty {
        Ty::Ref { name, args } => {
            out.insert(name.clone());
            args.iter().for_each(|a| collect_ty_refs(a, out));
        }
        Ty::Array(inner) => collect_ty_refs(inner, out),
        Ty::Tuple(items) | Ty::Union(items) => items.iter().for_each(|t| collect_ty_refs(t, out)),
        Ty::Record { key, value } => {
            collect_ty_refs(key, out);
            collect_ty_refs(value, out);
        }
        Ty::Object(fields) => fields.iter().for_each(|f| collect_ty_refs(&f.ty, out)),
        Ty::Prim(_) | Ty::Param(_) | Ty::Raw(_) | Ty::Unknown => {}
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::Config;
    use crate::ir::{Body, Decl, Field, Prim, SourceLoc, Ty};

    fn field(name: &str, ty: Ty) -> Field {
        Field {
            rust_name: name.into(),
            ts_name: name.into(),
            ty,
            optional: false,
            flatten: false,
            readonly: false,
            inline: false,
            docs: vec![],
        }
    }

    fn decl(name: &str, body: Body) -> Decl {
        Decl {
            rust_path: format!("crate::{name}"),
            ts_name: name.into(),
            docs: vec![],
            generics: vec![],
            body,
            loc: SourceLoc { file: "x.rs".into(), line: 1 },
        }
    }

    fn registry(decls: Vec<Decl>) -> Registry {
        let mut reg = Registry::default();
        for d in decls {
            reg.insert(d).expect("no clash in fixture");
        }
        reg
    }

    fn render(reg: &Registry, cfg: &Config) -> (BTreeMap<String, String>, Diagnostics) {
        let mut diags = Diagnostics::default();
        let files = render_all(reg, cfg, &mut diags);
        (files, diags)
    }

    #[test]
    fn every_file_starts_with_the_marker_and_ends_with_one_newline() {
        let reg = registry(vec![decl("A", Body::Struct(vec![field("v", Ty::Prim(Prim::Str))]))]);
        let (files, _) = render(&reg, &Config::new());
        let a = &files["A.ts"];
        assert!(a.starts_with(MARKER), "missing marker: {a}");
        assert!(a.ends_with("}\n"));
        assert!(!a.ends_with("\n\n"));
    }

    #[test]
    fn referenced_types_produce_import_lines() {
        let reg = registry(vec![
            decl("A", Body::Struct(vec![field("b", Ty::Ref { name: "B".into(), args: vec![] })])),
            decl("B", Body::Struct(vec![field("v", Ty::Prim(Prim::Str))])),
        ]);
        let (files, diags) = render(&reg, &Config::new());
        assert!(diags.is_empty());
        assert!(files["A.ts"].contains("import type { B } from \"./B\";"));
        assert!(!files["B.ts"].contains("import"));
    }

    #[test]
    fn import_extension_is_appended_when_configured() {
        let reg = registry(vec![
            decl("A", Body::Struct(vec![field("b", Ty::Ref { name: "B".into(), args: vec![] })])),
            decl("B", Body::Unit),
        ]);
        let (files, _) = render(&reg, &Config::new().import_extension(".js"));
        assert!(files["A.ts"].contains("from \"./B.js\";"));
    }

    #[test]
    fn self_reference_emits_no_import() {
        let reg = registry(vec![decl(
            "Node",
            Body::Struct(vec![field("next", Ty::Ref { name: "Node".into(), args: vec![] })]),
        )]);
        let (files, diags) = render(&reg, &Config::new());
        assert!(diags.is_empty());
        assert!(!files["Node.ts"].contains("import"));
    }

    #[test]
    fn generic_parameters_are_never_imported() {
        let mut d = decl("Page", Body::Struct(vec![field("v", Ty::Param("T".into()))]));
        d.generics = vec!["T".into()];
        let (files, diags) = render(&registry(vec![d]), &Config::new());
        assert!(diags.is_empty());
        assert!(!files["Page.ts"].contains("import"));
    }

    #[test]
    fn unresolvable_reference_is_a_diagnostic_not_a_silent_unknown() {
        let reg = registry(vec![decl(
            "A",
            Body::Struct(vec![field("v", Ty::Ref { name: "Ghost".into(), args: vec![] })]),
        )]);
        let (_, diags) = render(&reg, &Config::new());
        assert_eq!(diags.len(), 1);
        let d = diags.iter().next().unwrap();
        assert!(d.message.contains("unknown type `Ghost`"));
        assert!(d.help.as_ref().unwrap().contains("#[ts(type"));
    }

    #[test]
    fn index_barrel_reexports_every_type_sorted() {
        let reg = registry(vec![decl("B", Body::Unit), decl("A", Body::Unit)]);
        let (files, _) = render(&reg, &Config::new());
        assert_eq!(
            files["index.ts"],
            format!(
                "{MARKER}\nexport type {{ A }} from \"./A\";\nexport type {{ B }} from \"./B\";\n"
            )
        );
    }

    #[test]
    fn index_can_be_disabled() {
        let reg = registry(vec![decl("A", Body::Unit)]);
        let (files, _) = render(&reg, &Config::new().index(false));
        assert!(!files.contains_key("index.ts"));
    }
}

#[cfg(test)]
mod inline_tests {
    use super::*;
    use crate::config::Config;
    use crate::ir::{Body, Decl, Field, Prim, SourceLoc, Ty};

    fn field(name: &str, ty: Ty, inline: bool) -> Field {
        Field {
            rust_name: name.into(),
            ts_name: name.into(),
            ty,
            optional: false,
            flatten: false,
            readonly: false,
            inline,
            docs: vec![],
        }
    }

    fn decl(name: &str, body: Body) -> Decl {
        Decl {
            rust_path: format!("crate::{name}"),
            ts_name: name.into(),
            docs: vec![],
            generics: vec![],
            body,
            loc: SourceLoc { file: "x.rs".into(), line: 1 },
        }
    }

    fn registry(decls: Vec<Decl>) -> Registry {
        let mut reg = Registry::default();
        for d in decls {
            reg.insert(d).expect("no clash");
        }
        reg
    }

    fn render(reg: &Registry) -> (BTreeMap<String, String>, Diagnostics) {
        let mut diags = Diagnostics::default();
        let files = render_all(reg, &Config::new(), &mut diags);
        (files, diags)
    }

    #[test]
    fn inlined_field_splices_the_shape_and_drops_the_import() {
        let reg = registry(vec![
            decl(
                "A",
                Body::Struct(vec![field("b", Ty::Ref { name: "B".into(), args: vec![] }, true)]),
            ),
            decl("B", Body::Struct(vec![field("v", Ty::Prim(Prim::Str), false)])),
        ]);
        let (files, diags) = render(&reg);
        assert!(diags.is_empty(), "{diags:?}");
        let a = &files["A.ts"];
        assert!(!a.contains("import"), "inlined type must not be imported: {a}");
        assert!(a.contains("b: { v: string };"), "shape not spliced: {a}");
        // The inlined type still gets its own file; inlining is per-use.
        assert!(files.contains_key("B.ts"));
    }

    #[test]
    fn a_non_inlined_reference_still_imports() {
        let reg = registry(vec![
            decl(
                "A",
                Body::Struct(vec![field("b", Ty::Ref { name: "B".into(), args: vec![] }, false)]),
            ),
            decl("B", Body::Struct(vec![field("v", Ty::Prim(Prim::Str), false)])),
        ]);
        let (files, _) = render(&reg);
        assert!(files["A.ts"].contains("import type { B } from \"./B\";"));
        assert!(files["A.ts"].contains("b: B;"));
    }

    #[test]
    fn inlining_an_enum_is_a_diagnostic_not_a_wrong_shape() {
        let reg = registry(vec![
            decl(
                "A",
                Body::Struct(vec![field("e", Ty::Ref { name: "E".into(), args: vec![] }, true)]),
            ),
            decl(
                "E",
                Body::Enum { repr: crate::ir::EnumRepr::UnitOnly, variants: vec![] },
            ),
        ]);
        let (_, diags) = render(&reg);
        assert!(
            diags.iter().any(|d| d.message.contains("cannot inline")),
            "expected a diagnostic, got: {diags:?}"
        );
    }

    #[test]
    fn inlining_an_unknown_type_is_still_an_unknown_type_diagnostic() {
        let reg = registry(vec![decl(
            "A",
            Body::Struct(vec![field("g", Ty::Ref { name: "Ghost".into(), args: vec![] }, true)]),
        )]);
        let (_, diags) = render(&reg);
        assert!(diags.iter().any(|d| d.message.contains("unknown type `Ghost`")));
    }
}
